def _cov(check: str, tid: str, spec: Dict[str, str]) -> Dict[str, Dict[str, List[str]]]:
    """coverage entry: per capability id, per exercised dimension, evidence refs."""
    out: Dict[str, Dict[str, List[str]]] = {}
    for cap, dims in spec.items():
        bucket: Dict[str, List[str]] = {}
        for d in dims:
            if d in ("F", "R"):
                bucket[d] = [f"oracle:{check}", f"task:{tid}"]
            else:
                bucket[d] = [f"task:{tid}"]
        out[cap] = bucket
    return out



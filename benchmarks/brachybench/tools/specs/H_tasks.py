def _cov(check: Optional[str], tid: str,
         spec: Dict[str, str]) -> Dict[str, Dict[str, List[str]]]:
    out: Dict[str, Dict[str, List[str]]] = {}
    for cap in spec:
        dims = _COVER_DIMS.get(cap, "FRA")
        bucket: Dict[str, List[str]] = {}
        for d in dims:
            refs = [f"task:{tid}"]
            if check and check != "pred":
                refs = [f"oracle:{check}", f"task:{tid}"]
            bucket[d] = refs
        out[cap] = bucket
    return out


